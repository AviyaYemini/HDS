def _next_id(rng: random.Random) -> uuid.UUID:
    """A record id from the seeded generator.

    Two runs make the same ids, so the scheduler, which breaks ties by the smallest id, makes the
    same rosters.
    """
    return uuid.UUID(int=rng.getrandbits(128), version=4)


def _names(rng: random.Random, count: int) -> list[str]:
    """``count`` distinct invented full names."""
    pairs = [f"{first} {last}" for first in FIRST_NAMES for last in LAST_NAMES]
    return rng.sample(pairs, count)


async def _layer_exists(db: AsyncSession, org: Organisation) -> bool:
    """Whether the layer was added before, whole or in part."""
    found = await db.execute(
        select(User.id).where(User.organisation_id == org.id, User.email == MARKER)
    )
    return found.first() is not None


async def _load_records(db: AsyncSession, org: Organisation) -> dict[str, Any]:
    """The records a run before this one made, to pick up where it stopped."""

    async def users(pattern: str) -> list[User]:
        found = await db.execute(
            select(User)
            .where(User.organisation_id == org.id, User.email.like(pattern))
            .order_by(User.email)
        )
        return list(found.scalars())

    names = [entry[0] for entry in PROJECTS]
    found = await db.execute(
        select(Project).where(
            Project.organisation_id == org.id,
            Project.name.in_(names),
            Project.is_deleted.is_(False),
        )
    )
    by_name = {p.name: p for p in found.scalars()}
    return {
        "staff": await users("staff%@hds.test"),
        "managers": await users("mgr%@hds.test"),
        "projects": [by_name[name] for name in names],
        "types": await _active_types(db, org),
    }


async def _active_types(db: AsyncSession, org: Organisation) -> dict[str, ShiftType]:
    """The organisation's active shift types, by name."""
    found = await db.execute(
        select(ShiftType).where(ShiftType.organisation_id == org.id, ShiftType.is_active.is_(True))
    )
    return {t.name: t for t in found.scalars()}


def _user(
    db: AsyncSession,
    rng: random.Random,
    org: Organisation,
    email: str,
    name: str,
    role: UserRole,
    password_hash: str,
    *,
    client_id: uuid.UUID | None = None,
    rate: decimal.Decimal | None = None,
) -> User:
    # The repository's own step stamps an account created active (only it may write the activation
    # time) and stores the address as the app does; the id is the seed's, drawn in order.
    user = User(
        id=_next_id(rng),
        organisation_id=org.id,
        **UserRepository._with_activation(
            {
                "email": email,
                "full_name": name,
                "role": role,
                "client_id": client_id,
                "password_hash": password_hash,
                "default_hourly_rate": rate,
                "is_active": True,
                "is_deleted": False,
            }
        ),
    )
    db.add(user)
    return user


async def _records(
    db: AsyncSession,
    org: Organisation,
    rng: random.Random,
    today: datetime.date,
    password_hash: str,
) -> dict[str, Any]:
    """The plain records, inserted directly: people, clients, sites, projects and their links.

    Every account takes ``password_hash``, the base admin's: the same dev password, hashed once.
    """
    names = _names(rng, EMPLOYEES + MANAGERS + len(CLIENTS))
    clients = []
    for name, since in CLIENTS:
        client = Client(
            id=_next_id(rng),
            organisation_id=org.id,
            name=name,
            contract_start=datetime.date.fromisoformat(since),
            contact_name=names.pop(),
            is_active=True,
            is_deleted=False,
        )
        db.add(client)
        clients.append(client)
    sites = []
    for name, address in SITES:
        site = Site(
            id=_next_id(rng),
            organisation_id=org.id,
            name=name,
            address=address,
            timezone="Asia/Jerusalem",
        )
        db.add(site)
        sites.append(site)
    await db.flush()

    staff = [
        _user(
            db,
            rng,
            org,
            f"staff{n:02d}@hds.test",
            names.pop(),
            UserRole.employee,
            password_hash,
            rate=decimal.Decimal(rng.choice(("38.00", "42.00", "45.50", "48.00", "52.00"))),
        )
        for n in range(1, EMPLOYEES + 1)
    ]
    managers = [
        _user(
            db,
            rng,
            org,
            f"mgr{n}@hds.test",
            names.pop(),
            UserRole.manager,
            password_hash,
            rate=decimal.Decimal("60.00"),
        )
        for n in range(1, MANAGERS + 1)
    ]
    for n, client in enumerate(clients, start=1):
        _user(
            db,
            rng,
            org,
            f"client{n}@hds.test",
            client.contact_name or "",
            UserRole.client,
            password_hash,
            client_id=client.id,
        )
    await db.flush()

    groups = [Group(id=_next_id(rng), organisation_id=org.id, name=name) for name in GROUPS]
    quals = [
        Qualification(id=_next_id(rng), organisation_id=org.id, name=name)
        for name in QUALIFICATIONS
    ]
    db.add_all([*groups, *quals])
    await db.flush()
    for person in staff:
        for group in rng.sample(groups, rng.randint(0, 2)):
            await db.execute(insert(user_groups).values(user_id=person.id, group_id=group.id))
        for qual in rng.sample(quals, rng.randint(1, 2)):
            await db.execute(
                insert(user_qualifications).values(user_id=person.id, qualification_id=qual.id)
            )

    types = await _active_types(db, org)
    projects = []
    for index, (name, kind, client_at, site_at, rate, needs) in enumerate(PROJECTS):
        project = Project(
            id=_next_id(rng),
            organisation_id=org.id,
            client_id=clients[client_at].id,
            site_id=sites[site_at].id,
            name=name,
            type=kind,
            billing_rate=decimal.Decimal(rate),
            start_date=today - datetime.timedelta(days=120),
            is_deleted=False,
            managers_see_pay=index % 2 == 0,
        )
        db.add(project)
        await db.flush()
        for type_name in needs:
            await db.execute(
                insert(project_shift_types).values(
                    project_id=project.id, shift_type_id=types[type_name].id
                )
            )
        # Two managers each, so every manager has a few projects and some share one.
        for manager in (managers[index % MANAGERS], managers[(index + 1) % MANAGERS]):
            db.add(
                ProjectManager(organisation_id=org.id, project_id=project.id, user_id=manager.id)
            )
        projects.append(project)
    await db.flush()
    return {"staff": staff, "managers": managers, "projects": projects, "types": types}


async def _settings(
    factory: async_sessionmaker[AsyncSession],
    admin: User,
    records: dict[str, Any],
    today: datetime.date,
) -> None:
    """Needs, pay and special days, through the services an Admin uses."""
    async with factory() as db:
        needs = staffing_needs(db)
        for project, (_, _, _, _, _, by_type) in zip(records["projects"], PROJECTS, strict=True):
            items = [
                {"shift_type_id": records["types"][name].id, "weekday": weekday, "headcount": n}
                for name, people in by_type.items()
                for weekday, n in enumerate(people)
                if n > 0
            ]
            await needs.replace_needs(admin, project.id, items)
        pay = pay_settings_service(db)
        # One project pays more for rest days than the organisation does.
        await pay.change_project(
            admin, records["projects"][0].id, {"settings": {"rest_pct": decimal.Decimal("175.00")}}
        )
        days = special_days(db)
        horizon = today + datetime.timedelta(days=365)
        wanted = [
            (datetime.date.fromisoformat(iso), name, decimal.Decimal("150.00"))
            for iso, name in HOLIDAYS
            if today <= datetime.date.fromisoformat(iso) <= horizon
        ]
        # A company day inside the published weeks, so the pay report shows a premium.
        wanted.append(
            (
                _sunday_of(today) - datetime.timedelta(days=12),
                "יום החברה",
                decimal.Decimal("125.00"),
            )
        )
        there = set(
            (
                await db.execute(
                    select(SpecialDay.day).where(
                        SpecialDay.organisation_id == admin.organisation_id,
                        SpecialDay.project_id.is_(None),
                    )
                )
            ).scalars()
        )
        for day, name, rate in wanted:
            if day not in there:  # a day already there, the developer's or an earlier run's, stays
                await days.create_organisation_day(
                    admin, {"day": day, "name": name, "rate_pct": rate}
                )
        await db.commit()


def _entries(
    rng: random.Random, first: datetime.date, types: Sequence[ShiftType], *, busy: bool = False
) -> list[dict[str, Any]]:
    """One person's week: a day or two they cannot work, a wish or two, now and then leave.

    A ``busy`` week (next week's, the proposal's) is harder to staff: most of the people are
    on reserve duty from Thursday, and most block a weekend day, so some places stay empty, each
    for its own reason.
    """
    days = [first + datetime.timedelta(days=n) for n in range(7)]
    blank = {"absence_kind": None, "shift_type_id": None, "weekday": None}
    out: list[dict[str, Any]] = []
    if busy and rng.random() < 0.7:
        out.append(
            {
                **blank,
                "kind": "absence",
                "absence_kind": "reserve_duty",
                "starts_on": days[4],
                "ends_on": days[6],
            }
        )
        return out
    if busy and rng.random() < 0.8:
        weekend = rng.choice(days[5:])
        out.append({**blank, "kind": "blocked", "starts_on": weekend, "ends_on": weekend})
    if rng.random() < 0.08:
        start = rng.choice(days[:5])
        out.append(
            {
                **blank,
                "kind": "absence",
                "absence_kind": rng.choice(("leave", "sick", "reserve_duty")),
                "starts_on": start,
                "ends_on": start + datetime.timedelta(days=2),
            }
        )
        return out
    taken = {e["starts_on"] for e in out}
    for day in rng.sample([d for d in days if d not in taken], rng.randint(1, 2)):
        out.append({**blank, "kind": "blocked", "starts_on": day, "ends_on": day})
    free = [d for d in days if all(e["starts_on"] != d for e in out)]
    for day in rng.sample(free, min(len(free), rng.randint(0, 2))):
        kind = "open" if rng.random() < 0.7 else "close"
        out.append(
            {
                **blank,
                "kind": kind,
                "starts_on": day,
                "ends_on": day,
                "shift_type_id": rng.choice(types).id,
            }
        )
    return out


async def _availability(
    factory: async_sessionmaker[AsyncSession],
    org: Organisation,
    admin: User,
    staff: Sequence[User],
    types: Sequence[ShiftType],
    rng: random.Random,
    this_week: datetime.date,
) -> None:
    """Windows from four weeks back to next week; the past submitted, next week mostly so.

    A week another window already covers, even in part, uses that window: windows never overlap.
    Only a window this seed made itself, and still open, is marked by the people; any other is
    entered for them by the Admin, who may enter anyone's availability at any time.
    """
    marked_by_people: set[uuid.UUID] = set()
    async with factory() as db:
        windows: list[tuple[datetime.date, SubmissionWindow]] = []
        for offset in range(-PAST_WEEKS, 2):
            first = this_week + datetime.timedelta(weeks=offset)
            last = first + datetime.timedelta(days=6)
            found = (
                (
                    await db.execute(
                        select(SubmissionWindow)
                        .where(
                            SubmissionWindow.organisation_id == org.id,
                            SubmissionWindow.starts_on <= last,
                            SubmissionWindow.ends_on >= first,
                        )
                        .order_by(SubmissionWindow.starts_on)
                    )
                )
                .scalars()
                .first()
            )
            if found is None:
                # Next week's deadline is its first morning, so it is open now; the rest closed.
                deadline = datetime.datetime.combine(
                    first if offset == 1 else first - datetime.timedelta(days=1),
                    datetime.time(9, 0) if offset == 1 else datetime.time(0, 0),
                    SITE_ZONE,
                )
                found = SubmissionWindow(
                    id=_next_id(rng),
                    organisation_id=org.id,
                    starts_on=first,
                    ends_on=last,
                    deadline=deadline,
                )
                db.add(found)
                if offset == 1:
                    marked_by_people.add(found.id)
            windows.append((first, found))
        await db.commit()

    for first, window in windows:
        async with factory() as db:
            entered = (
                await db.execute(
                    select(AvailabilityEntry.id).where(
                        AvailabilityEntry.user_id == staff[0].id,
                        AvailabilityEntry.starts_on >= first,
                        AvailabilityEntry.starts_on <= first + datetime.timedelta(days=6),
                    )
                )
            ).first()
            if entered is not None:
                continue  # this week was entered by an earlier run
            by_people = window.id in marked_by_people
            entries, submissions = availability_service(db), submission_service(db)
            for person in staff:
                for entry in _entries(rng, first, types, busy=first > this_week):
                    await entries.add_entry(person if by_people else admin, person.id, entry)
                if by_people:
                    if rng.random() < 0.85:  # the rest are late
                        await submissions.submit(person, window.id)
                elif rng.random() < 0.95:
                    await submissions.submit_on_behalf(admin, person.id, window.id)
            await db.commit()


async def _week(
    factory: async_sessionmaker[AsyncSession],
    admin: User,
    projects: Sequence[Project],
    first: datetime.date,
    *,
    publish: bool,
) -> uuid.UUID:
    """Generate a week for the wide projects with the greedy solver; accept and publish it.

    A run an earlier seed made for the week is picked up where it stopped.
    """
    ids = [str(p.id) for p in projects]
    async with factory() as db:
        earlier = [
            job
            for job in (
                await db.execute(
                    select(ScheduleJob)
                    .where(
                        ScheduleJob.organisation_id == admin.organisation_id,
                        ScheduleJob.first_day == first,
                        ScheduleJob.status.in_(("queued", "running", "succeeded")),
                    )
                    .order_by(ScheduleJob.created_at)
                )
            ).scalars()
            if sorted(job.project_ids) == sorted(ids)
        ]
        if earlier:
            job_id = earlier[-1].id
        else:
            job = await job_service(db).create(
                admin,
                {
                    "first_day": first,
                    "last_day": first + datetime.timedelta(days=6),
                    "project_ids": [p.id for p in projects],
                    "solver": "greedy",
                },
            )
            await db.commit()
            job_id = job.id
    while await run_once(factory) is not None:
        pass
    async with factory() as db:
        status, error = (
            await db.execute(
                select(ScheduleJob.status, ScheduleJob.error_code).where(ScheduleJob.id == job_id)
            )
        ).one()
    if status != "succeeded":
        # Stop here, loudly: the next run makes a new run for the week (a failed one is not reused).
        raise RuntimeError(f"the run for the week of {first} ended {status} ({error})")
    if publish:
        async with factory() as db:
            state = (
                await db.execute(select(ScheduleJob.proposal_state).where(ScheduleJob.id == job_id))
            ).scalar_one()
            if state == "open":
                await job_service(db).accept(admin, job_id)
                await db.commit()
        async with factory() as db:
            roster = roster_service_for(db)
            for project in projects:
                await roster.publish(admin, project.id, first, first + datetime.timedelta(days=6))
            await db.commit()
    return job_id


async def _manual_edits(
    factory: async_sessionmaker[AsyncSession],
    admin: User,
    projects: Sequence[Project],
    this_week: datetime.date,
) -> None:
    """Three hand placements that break a rule; two kept with a recorded reason, one left open.

    Each puts someone on their own morning's project on the night before it, so the roster names
    the rule it breaks (too little rest, or a day they blocked or would rather not work).
    """
    async with factory() as db:
        done = await db.execute(select(Assignment.id).where(Assignment.note == HAND_NOTE).limit(1))
        if done.first() is not None:
            return  # placed by an earlier run
    starts = datetime.datetime.combine(this_week, datetime.time(), SITE_ZONE)
    ends = starts + datetime.timedelta(days=7)
    async with factory() as db:
        shifts = (
            (
                await db.execute(
                    select(Shift)
                    .where(
                        Shift.project_id.in_([p.id for p in projects]),
                        Shift.starts_at >= starts.astimezone(datetime.UTC),
                        Shift.starts_at < ends.astimezone(datetime.UTC),
                    )
                    .order_by(Shift.starts_at, Shift.id)
                )
            )
            .scalars()
            .all()
        )
        on: dict[uuid.UUID, set[uuid.UUID]] = {}
        for a in (
            await db.execute(
                select(Assignment).where(Assignment.shift_id.in_([s.id for s in shifts]))
            )
        ).scalars():
            on.setdefault(a.shift_id, set()).add(a.user_id)
    # Someone on a morning placed on the same project's night before it as well: too little rest
    # between them. One person per night, on three different nights.
    pairs: list[tuple[Shift, uuid.UUID]] = []
    for night in (s for s in shifts if s.ends_at.astimezone(SITE_ZONE).hour == 7):
        morning = next(
            (
                m
                for m in shifts
                if m.project_id == night.project_id and m.starts_at == night.ends_at
            ),
            None,
        )
        free = sorted(on.get(morning.id, set()) - on.get(night.id, set())) if morning else []
        if free:
            pairs.append((night, free[0]))
        if len(pairs) == 3:
            break
    for index, (night, person) in enumerate(pairs):
        async with factory() as db:
            judged = await roster_service_for(db).assign(
                admin, night.id, person, note=HAND_NOTE, alert="none"
            )
            await db.commit()
        broken = [w for w in judged.warnings if w.get("employee_id") == person]
        if broken and index < len(pairs) - 1:
            async with factory() as db:
                await roster_tools_for(db).override(
                    admin, judged.record.id, broken[0]["code"], "אין מחליף זמין, באישור העובד"
                )
                await db.commit()


