"""The wider development data, on top of the base seed (``seed_dev --wide``; stabilization S21-S23).

Run with:
    uv run python -m hds.scripts.seed_dev --wide

The base seed stays as it is, for the tests and the e2e specs. This adds, in the same
organisation, enough that every screen from 001 to 008 has something to show:

    People:     40 employees, 4 managers (mgr1..mgr4@hds.test), 4 client users
                (client1..client4@hds.test), all with the dev password, invented Israeli names
    Clients:    4 invented companies; 6 sites; 8 projects (5 security, 3 training), each with
                its shift types, staffing needs and two managers; groups and qualifications
    Pay:        each employee's hourly rate; one project with its own rest premium; the
                coming year's Israeli holidays as special days, and a company day in the seeded
                weeks, so pay shows premiums
    Availability: windows for four past weeks, this week and next; past weeks submitted on the
                people's behalf, next week's marked by the people themselves, a few not yet
                submitted
    Rosters:    four past weeks and this one, generated by the scheduler (greedy), accepted and
                published through the services, so they obey every rule and pay is computed as
                in production; next week, when most people are on reserve duty from Thursday,
                left as a proposal to review, with empty places and their reasons
    Edits:      a few manual assignments that break a rule, some kept with a recorded reason
    Views:      saved views on the staff and projects tables

Deterministic: a fixed random seed, and every date relative to today. Running it again adds
nothing: the layer is skipped when its first project exists. Needs the base seed first, and
writes through the services wherever the app does, so it never runs against production: the
accounts share the published dev password.

Layer: scripts. May use services, repositories and models; MUST NOT import routers.
"""

