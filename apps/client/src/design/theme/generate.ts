/**
 * The theme generator (specs/007-ux-redesign FR-061, research R3, task T016).
 *
 * Reads the DTCG 2025.10 token files (`src/design/tokens/*.tokens.json`) and writes
 * `theme.generated.ts`: every `{reference}` resolved, colours as `#RRGGBB`, dimensions and
 * durations as plain numbers (px, ms), easings as their four control points, font families as
 * arrays. `scripts/build-theme.ts` writes the file; `tests/unit/theme.generated.test.ts` fails when
 * the committed file drifts from the tokens (`pnpm theme:check` does the same from the shell).
 *
 * Pure: no React, no React Native, so Node can run it directly.
 */

type Json = { [key: string]: unknown };

/** The three token tiers, parsed. */
export interface TokenFiles {
  base: Json;
  semantic: Json;
  component: Json;
}

const REFERENCE = /^\{([^}]+)\}$/;

function at(tree: Json, path: string): unknown {
  let node: unknown = tree;
  for (const part of path.split(".")) {
    if (typeof node !== "object" || node === null) return undefined;
    node = (node as Json)[part];
  }
  return node;
}

/** Resolve one DTCG `$value` into a plain value, following references through the tiers. */
export function resolveValue(value: unknown, files: TokenFiles, scope: Json, hops = 0): unknown {
  if (hops > 16) throw new Error(`token reference loop near ${JSON.stringify(value)}`);
  if (typeof value === "string") {
    const reference = REFERENCE.exec(value);
    if (!reference) return value;
    const path = reference[1]!;
    const target =
      (at(scope, path) as Json | undefined) ??
      (at(files.base, path) as Json | undefined) ??
      (at(files.component, path) as Json | undefined) ??
      (at(files.semantic, path) as Json | undefined);
    if (!target || typeof target !== "object" || !("$value" in target)) {
      throw new Error(`unresolved token reference ${value}`);
    }
    return resolveValue((target as Json).$value, files, scope, hops + 1);
  }
  if (Array.isArray(value)) return value.map((item) => resolveValue(item, files, scope, hops + 1));
  if (value && typeof value === "object") {
    const object = value as Json;
    // A colour: keep its hex, upper-cased.
    if ("colorSpace" in object && typeof object.hex === "string") return object.hex.toUpperCase();
    // A dimension or duration: a number in px or ms.
    if ("unit" in object && typeof object.value === "number") {
      if (object.unit === "px" || object.unit === "ms") return object.value;
      throw new Error(`unsupported unit ${String(object.unit)}`);
    }
    const out: Json = {};
    for (const [key, item] of Object.entries(object)) out[key] = resolveValue(item, files, scope, hops + 1);
    return out;
  }
  return value;
}

/** Walk a DTCG group, replacing each token by its resolved value and dropping `$` metadata. */
export function resolveGroup(group: Json, files: TokenFiles, scope: Json): Json {
  const out: Json = {};
  for (const [key, value] of Object.entries(group)) {
    if (key.startsWith("$")) continue;
    if (typeof value !== "object" || value === null) continue;
    const node = value as Json;
    out[key] = "$value" in node ? resolveValue(node.$value, files, scope) : resolveGroup(node, files, scope);
  }
  return out;
}

const HEADER = `/**
 * GENERATED by scripts/build-theme.ts from src/design/tokens/*.tokens.json. Do not edit by hand:
 * change the tokens and run \`pnpm theme:build\`; \`pnpm theme:check\` and the unit tests fail on
 * drift (specs/007-ux-redesign FR-061, research R3).
 */
`;

function literal(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

/** The text of `theme.generated.ts` for these token files. */
export function generateTheme(files: TokenFiles): string {
  const palette = resolveGroup(files.base.palette as Json, files, files.base);
  const font = resolveGroup(files.base.font as Json, files, files.base);
  const motion = resolveGroup(files.base.motion as Json, files, files.base);
  const component = resolveGroup(files.component, files, files.component);
  const themes: Json = {};
  for (const [name, theme] of Object.entries(files.semantic.theme as Json)) {
    themes[name] = resolveGroup(theme as Json, files, theme as Json);
  }
  const minimum = ((files.semantic.$extensions as Json).hds as Json).minimum;
  return [
    HEADER,
    `/** The raw palette, by name. */`,
    `export const palette = ${literal(palette)} as const;`,
    ``,
    `/** Font families (first is the Plex face) and the three weights. */`,
    `export const font = ${literal(font)} as const;`,
    ``,
    `/** Durations in milliseconds and easings as cubic-bezier control points. */`,
    `export const motion = ${literal(motion)} as const;`,
    ``,
    `/** Sizes, shapes, density and the component transitions (px and ms). */`,
    `export const component = ${literal(component)} as const;`,
    ``,
    `/** The four themes' colour roles, as #RRGGBB. */`,
    `export const themes = ${literal(themes)} as const;`,
    ``,
    `/** The contrast each theme guarantees for text and icons. */`,
    `export const contrastMinimum = ${literal(minimum)} as const;`,
    ``,
    `export type ThemeName = keyof typeof themes;`,
    `export type ThemeColors = (typeof themes)[ThemeName];`,
    `export type Density = keyof typeof component.density;`,
    ``,
  ].join("\n");
}
